export function getServicePage(slug: string): ServicePage | undefined {
  return SERVICE_PAGES.find((item) => item.slug === slug);
}

export function servicePagesBySlugs(slugs: readonly string[]): ServicePage[] {
  return slugs
    .map((slug) => getServicePage(slug))
    .filter((item): item is ServicePage => Boolean(item));
}

export function serviceCtaHref(page: ServicePage): string {
  if (page.relatedPlan) return `/?plan=${page.relatedPlan}#contact`;
  return "/#contact";
}

export function serviceHrefByTitle(title: string): string | undefined {
  const normalized = title.toLowerCase();
  if (normalized.includes("магазин") || normalized.includes("e-commerce")) {
    return "/poslugy/internet-magazyn";
  }
  if (normalized.includes("telegram") || normalized.includes("бот")) {
    return "/poslugy/telegram-boty";
  }
  if (normalized.includes("контекст") || normalized.includes("реклам") || normalized.includes("google ads")) {
    return "/poslugy/kontekstna-reklama";
  }
  if (normalized.includes("seo") || normalized.includes("просуван")) {
    return "/poslugy/seo";
  }
  if (normalized.includes("мобіль") || normalized.includes("застосун") || normalized.includes("додат")) {
    return "/poslugy/mobilni-zastosunky";
  }
  if (
    normalized.includes("crm") ||
    normalized.includes("erp") ||
    normalized.includes("автоматиз") ||
    normalized.includes("внутрішн")
  ) {
    return "/poslugy/crm-erp";
  }
  if (normalized.includes("лендинг")) {
    return "/poslugy/lendingy";
  }
  if (normalized.includes("корпоратив")) {
    return "/poslugy/korporatyvni-sajty";
  }
  if (normalized.includes("дизайн") || normalized.includes("ui") || normalized.includes("ux")) {
    return "/poslugy/dyzajn";
  }
  if (normalized.includes("сайт") || normalized.includes("розробк")) {
    return "/poslugy/sajty";
  }
  return "/poslugy";
}
